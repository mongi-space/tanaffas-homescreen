const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

const getLanguageSwitchedPath = (currentPath: string, newLang: Language): string => {
  const path = currentPath || '/';
  
  // If path starts with /ar, /en, or /fr
  const prefixMatch = path.match(/^\/(ar|en|fr)(\/.*|$)/i);
  if (prefixMatch) {
    const rest = prefixMatch[2] || '';
    return `/${newLang}${rest === '' || rest === '/' ? '/' : rest}`;
  }
  
  // If path has no language prefix
  if (path === '/' || path === '') {
    return `/${newLang}/`;
  }
  return `/${newLang}${path.startsWith('/') ? path : '/' + path}`;
};

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    if (typeof window !== 'undefined') {
      const pathname = window.location.pathname.toLowerCase();
      if (pathname === '/en' || pathname.startsWith('/en/')) {
        return 'en';
      }
      if (pathname === '/fr' || pathname.startsWith('/fr/')) {
        return 'fr';
      }
      if (pathname === '/ar' || pathname.startsWith('/ar/')) {
        return 'ar';
      }
      const saved = localStorage.getItem('tanaffas_lang');
      if (saved === 'ar' || saved === 'en' || saved === 'fr') {
        return saved;
      }
    }
    return 'ar';
  });

  const setLanguage = (newLang: Language) => {
    setLanguageState(newLang);
    if (typeof window !== 'undefined') {
      localStorage.setItem('tanaffas_lang', newLang);
      document.documentElement.dir = newLang === 'ar' ? 'rtl' : 'ltr';
      document.documentElement.lang = newLang;

      const newPath = getLanguageSwitchedPath(window.location.pathname, newLang);
      if (window.location.pathname !== newPath) {
        window.history.pushState({}, '', newPath);
      }
    }
  };

  useEffect(() => {
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = language;
  }, [language]);

  const t = (key: string) => {
    return translations[language][key] || key;
  };

  const getLocale = () => {
    return language === 'ar' ? 'ar-u-nu-latn' : (language === 'fr' ? 'fr-FR' : 'en-US');
  };

  const formatDate = (date: Date) => {
    return date.toLocaleDateString(getLocale());
  };

  const formatDateTime = (date: Date) => {
    return date.toLocaleString(getLocale());
  };

  const formatNumber = (num: number) => {
    return new Intl.NumberFormat(getLocale()).format(num);
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, formatDate, formatDateTime, formatNumber }}>
      <div dir={language === 'ar' ? 'rtl' : 'ltr'} lang={language}>
        {children}
      </div>
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
